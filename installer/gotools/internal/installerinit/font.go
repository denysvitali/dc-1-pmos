// glyph maps a byte to its columns, blanking anything outside the table.
func glyph(b byte) *[5]byte {
	if b < 0x20 || int(b-0x20) >= len(statusFont) {
		return &statusFont[0]
	}
	return &statusFont[b-0x20]
}
